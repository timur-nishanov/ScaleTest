/**
 * Глобальная конфигурация интерактива.
 *
 * Все «спорные» значения (где ТЗ и макеты расходятся) вынесены сюда,
 * чтобы менять одним числом — см. docs/DESIGN-NOTES.md, раздел «Расхождения».
 */

/** Дизайн-координаты: макеты нарисованы в 3840×2160, вся вёрстка ведётся 1:1. */
export const DESIGN_W = 3840
export const DESIGN_H = 2160

/** Таймер на задачу, сек. Решение заказчика 26.08: 60, как в прототипе
 * (в макетах статичные 00:45 — просто нарисованный момент времени). */
export const TIMER_SECONDS = 60

/** Красная зона таймера, последние N секунд. */
export const TIMER_WARN_SECONDS = 10

/** Простой до попапа «Вы ещё здесь?», сек (не на attract-экране).
 * Было 15 по ТЗ — увеличено до 30 по фидбеку заказчика 26.08. */
export const IDLE_PROMPT_AFTER_S = 30

/** Простой после попапа до автосброса на заставку, сек. */
export const IDLE_RESET_AFTER_S = 15

/** Скейл кликабельных элементов при нажатии (стейты в Figma). */
export const PRESS_SCALE = 0.94

/** Шаг колеса карточек, градусы между соседними карточками (из макета). */
export const WHEEL_STEP_DEG = 15

export const FLAGS = {
  /**
   * Проверять ли порядок сервисов в слотах (а не только набор).
   * В попапе результата подсветка идёт по-слотно — считаем, что порядок важен.
   * Открытый вопрос в ТЗ — переключается здесь.
   */
  orderMatters: true,
  /** Кнопка случайного выбора в режиме «Выбрать из готового» (есть в макете 2334:5831). */
  randomInReadyMode: true,
} as const

export type AppMode = 'kiosk' | 'web'

/** kiosk — тач-экран на стенде; web — версия для рассылки пользователям. */
export const APP_MODE: AppMode =
  typeof location !== 'undefined' &&
  new URLSearchParams(location.search).get('mode') === 'web'
    ? 'web'
    : 'kiosk'
